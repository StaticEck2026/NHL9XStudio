/**
 * Build data/frames95snes.asm: the SPF groups and the SPA sequences of NHL 95 on the SNES, from the NHL95SNES source.
 *
 * SPF equates come from src/frames95s.asm, one SPA list from each src/data/tables/SPA*.asm file (in the order
 * src/banks/bC4_logic_collide.asm includes them, which is the ROM order). Every frame number is written out as a
 * number; the names stay in the labels and comments. A sequence is eight direction pointers, a flags word, then
 * (frame, time) pairs ending in a negative time, as in the 93 and 94 SNES listings.
 *
 * Usage: node tools/build-snes95-frames.js [path to an NHL95SNES clone]   (default /tmp/snes/95)
 */
const fs = require('fs');
const path = require('path');
const { parseFrames } = require('../lib/parse-frames');

const SRC = process.argv[2] || process.env.SNES95 || '/tmp/snes/95';
const OUT = path.join(__dirname, '..', 'data', 'frames95snes.asm');

function read(rel) {
  return fs.readFileSync(path.join(SRC, rel), 'utf8').split(/\r?\n/);
}

function split(line) {
  const i = line.indexOf(';');
  return i < 0 ? { code: line.trim(), comment: '' } : { code: line.slice(0, i).trim(), comment: line.slice(i + 1).trim() };
}

// SPF equates: a name, =, a number, the first comment line.
const spf = new Map();
const spfOrder = [];
for (const line of read('src/frames95s.asm')) {
  const m = /^(SPF\w+)\s*=\s*(\$[0-9A-Fa-f]+|\d+)\s*(?:;\s*(.*))?$/.exec(line);
  if (!m) continue;
  const value = m[2][0] === '$' ? parseInt(m[2].slice(1), 16) : Number(m[2]);
  spf.set(m[1], value);
  spfOrder.push({ name: m[1], value, comment: m[3] || '' });
}

function evaluate(expr) {
  const m = /^(SPF\w+)(?:\s*\+\s*(\d+|\$[0-9A-Fa-f]+))?$/.exec(expr.trim());
  if (m) {
    if (!spf.has(m[1])) throw new Error('unknown ' + m[1]);
    const add = m[2] ? (m[2][0] === '$' ? parseInt(m[2].slice(1), 16) : Number(m[2])) : 0;
    return spf.get(m[1]) + add;
  }
  if (/^-?\d+$/.test(expr.trim())) return Number(expr.trim());
  if (/^\$[0-9A-Fa-f]+$/.test(expr.trim())) return parseInt(expr.trim().slice(1), 16);
  throw new Error('cannot evaluate ' + expr);
}

// The ROM order of the SPA lists.
const order = [];
for (const line of read('src/banks/bC4_logic_collide.asm')) {
  const m = /tables\/(SPA\w+)\.asm/.exec(line);
  if (m) order.push(m[1]);
}

const out = [];
out.push('; SPF groups and SPA sequences for NHL 95 on the SNES.');
out.push('; Generated by tools/build-snes95-frames.js from the NHL95SNES source: src/frames95s.asm for the SPF groups and the');
out.push('; SPA*.asm lists of src/data/tables, in the order the ROM holds them. Frame numbers are the game\'s own (an index of');
out.push('; FrameTileSource / FrameBankLayout, 1060 frames); a sequence is eight direction pointers, a flags word, then');
out.push('; (frame, time) pairs ending in a negative time.');
out.push('');
const width = Math.max(...spfOrder.map((e) => e.name.length));
for (const e of spfOrder) {
  out.push(e.name.padEnd(Math.max(width, 8)) + '= ' + e.value + (e.comment ? '\t; ' + e.comment : ''));
}
out.push('');
out.push('SPAList:');
out.push('\tdc.w\t0');
out.push('');

for (const file0 of order) {
  const file = path.join('src/data/tables', file0 + '.asm');
  // a file holds one list, or two (SPAHold / SPAHold2, SPAgready / SPAgready2)
  const lists = [];
  for (const line of read(file)) {
    const { code, comment } = split(line);
    const top = /^(SPA\w+):$/.exec(code);
    if (top) lists.push({ name: top[1], title: comment, lines: [] });
    else if (code && lists.length) lists[lists.length - 1].lines.push(code);
  }
  for (const list of lists) {
    let flags = 0;
    const dirs = [];
    const labels = new Map();
    let current = null;
    let sawFlags = false;
    for (const code of list.lines) {
      let m = /^(\.?\w+):$/.exec(code);
      if (m) { current = []; labels.set(m[1], current); continue; }
      m = /^dw\s+(.*)$/.exec(code);
      if (!m) continue;
      const items = m[1].split(',').map((x) => x.trim());
      if (!current && !dirs.length) {
        for (const item of items) dirs.push(item);
      } else if (!current && !sawFlags) {
        flags = evaluate(items[0]);
        sawFlags = true;
      } else if (current) {
        try { for (const item of items) current.push(evaluate(item)); } catch (e) { throw new Error(list.name + ': ' + e.message); }
      }
    }
    const labelNames = [...labels.keys()];
    out.push(list.name + '\t= *-SPAList' + (list.title ? '\t; ' + list.title.replace(/^per direction \(facedir & 7, \* 2\): /, '') : ''));
    out.push('.t');
    out.push('\tdc.w\t' + dirs.map((d) => '.' + labelNames.indexOf(d) + '-.t').join(','));
    out.push('\tdc.w\t' + flags);
    labelNames.forEach((l, i) => {
      out.push('.' + i + '\tdc.w\t' + labels.get(l).join(','));
    });
    out.push('');
  }
}
const text = out.join('\n');
fs.writeFileSync(OUT, text);
const parsed = parseFrames(text);
console.log('wrote', OUT, order.length, 'files', spfOrder.length, 'SPF groups');
console.log(Object.keys(parsed).join(','));
